#!/usr/bin/env python3
"""Build-time URL contract. Nothing is fetched or configured remotely at runtime."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
import sys
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]


def load_contract(root: Path) -> dict:
    contract = json.loads((root / "config/site-urls.json").read_text())
    if not isinstance(contract, dict) or set(contract) != {"version", "origin", "home", "privacy"}:
        raise ValueError("Invalid URL contract schema")
    if contract["version"] != 1 or contract["origin"] != "https://bluetoothdisable.app" or contract["home"] != "/":
        # The renderer's origin stays fixed; this is not a remotely configurable browser.
        raise ValueError("Unsupported URL contract version, origin or home")
    privacy = contract["privacy"]
    if not isinstance(privacy, dict) or set(privacy) != {"ru", "en"}:
        raise ValueError("Privacy routes must cover exactly RU and EN")
    for lang, route in privacy.items():
        if not isinstance(route, str) or not re.fullmatch(rf"/privacy/{lang}/[a-z][a-z0-9-]*", route):
            raise ValueError("Privacy routes must be unambiguous extensionless paths")
    return contract


def replace_once(text: str, pattern: str, replacement, label: str) -> str:
    updated, count = re.subn(pattern, replacement if callable(replacement) else lambda _: replacement, text)
    if count != 1:
        raise ValueError(f"Expected exactly one {label}, found {count}")
    return updated


def outputs(root: Path, contract: dict) -> dict[str, str]:
    origin, home, privacy = contract["origin"], contract["home"], contract["privacy"]
    paths = list(privacy.values())
    legacy = [path + ".html" for path in paths]
    result = {
        "docs/pages/sitemap.xml": '<?xml version="1.0" encoding="UTF-8"?>\n'
            '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
            + "".join(f"<url><loc>{origin}{path}</loc></url>\n" for path in [home, *paths])
            + "</urlset>\n",
        "docs/pages/_redirects": "# Generated by scripts/sync_site_urls.py; legacy addresses only.\n"
            + f"/index.html {home} 301\n"
            + "".join(f"{old} {new} 301\n" for old, new in zip(legacy, paths)),
    }
    host = urlsplit(origin).hostname
    values = ",\n            ".join(json.dumps(path) for path in [*paths, *legacy])
    result["app/src/main/java/com/pulse/bluetoothdisable/privacy/PublicSiteUrls.java"] = f'''package com.pulse.bluetoothdisable.privacy;

import java.util.Arrays;
import java.util.Collections;
import java.util.List;

/** Generated by scripts/sync_site_urls.py; compile-time constants, never remote configuration. */
final class PublicSiteUrls {{
    static final String HOST = "{host}";
    static final String ORIGIN = "{origin}";
    static final String PRIVACY_RU = "{privacy['ru']}";
    static final String PRIVACY_EN = "{privacy['en']}";
    static final List<String> DOCUMENT_PATHS = Collections.unmodifiableList(Arrays.asList(
            {values}));
    private PublicSiteUrls() {{}}
    static String privacyForLanguage(String language) {{
        return ORIGIN + ("ru".equals(language) ? PRIVACY_RU : PRIVACY_EN);
    }}
}}
'''
    canonical = r'<link\s+rel="canonical"\s+href="[^"]+"\s*/?>'
    for lang, path in privacy.items():
        source = "docs/pages" + path + ".html"
        text = (root / source).read_text()
        result[source] = replace_once(text, canonical,
            f'<link rel="canonical" href="{origin}{path}">', source + " canonical")
        stub = "docs/github-pages-redirect" + path + ".html"
        # GitHub Pages keeps old files for external links, but sends users straight to the new URL.
        result[stub] = (root / stub).read_text().replace(origin + path + ".html", origin + path)
    language_js = (root / "docs/pages/assets/js/language.js").read_text()
    if "link.href = publicPrivacyUrls[current];" not in language_js:
        raise ValueError("Language switching must use the compile-time URL registry")
    language_js = replace_once(language_js,
        r'// BEGIN GENERATED PRIVACY URLS\n.*?\n  // END GENERATED PRIVACY URLS',
        '// BEGIN GENERATED PRIVACY URLS\n  const publicPrivacyUrls = Object.freeze('
        + json.dumps({lang: origin + path for lang, path in privacy.items()})
        + ');\n  // END GENERATED PRIVACY URLS', 'language URL registry')
    result["docs/pages/assets/js/language.js"] = language_js
    language_version = hashlib.sha256(language_js.encode()).hexdigest()[:10]
    index = (root / "docs/pages/index.html").read_text()
    index = replace_once(index, canonical, f'<link rel="canonical" href="{origin}{home}">', "home canonical")
    index = replace_once(index, r'(<a\b[^>]*\bid="privacy-link"[^>]*\bhref=")[^"]+("[^>]*>)',
        # The fixed no-JavaScript fallback points to the same canonical RU page.
        lambda match: match.group(1) + privacy["ru"] + match.group(2), "privacy fallback link")
    index = replace_once(index, r'<script src="assets/js/language\.js\?v=[^"]+" defer>\s*</script>',
        f'<script src="assets/js/language.js?v={language_version}" defer>\n</script>', "language script")
    result["docs/pages/index.html"] = index
    for source in ["docs/github-pages-redirect/index.html", "docs/github-pages-redirect/404.html"]:
        stub = (root / source).read_text()
        # The fallback 404 handler needs an exact mapping, not a wildcard suffix rewrite.
        mapping = "var aliases = {\n" + ",\n".join(
            f"        '{old}': '{new}'" for old, new in zip(["/index.html", *legacy], [home, *paths])
        ) + "\n      };"
        result[source] = replace_once(stub, r"var aliases = \{[\s\S]*?\};", mapping, source + " aliases")
    return result


def sync(root: Path, write: bool = False) -> list[str]:
    changed = []
    for relative, expected in outputs(root, load_contract(root)).items():
        path = root / relative
        if not path.exists() or path.read_text() != expected:
            changed.append(relative)
            if write:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(expected)
    return changed


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        changed = sync(ROOT, args.write)
    except (ValueError, OSError) as error:
        print(f"URL contract error: {error}", file=sys.stderr)
        return 1
    if changed:
        print(("Updated: " if args.write else "URL contract drift: ") + ", ".join(changed))
        return 0 if args.write else 1
    print("Site metadata, redirects and Android URLs agree with the public URL contract.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
